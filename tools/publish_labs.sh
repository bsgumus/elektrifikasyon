#!/bin/sh
# Publish the site to the Ember Labs repository (ember-labs-org/turkiye-electrification-simulator).
#
# The Labs repo holds ONLY the site: docs/ (four pages, config.js, assets/style.css, .nojekyll).
# This script mirrors docs/ from here into the Labs clone, applies the Labs branding overlay
# (labs/config.js -> docs/config.js, labs/style.css -> docs/assets/style.css), verifies it,
# commits docs/ and pushes. worker/, tools/, labs/ and docs/CNAME are never copied.
#
# One-time setup:  git clone https://github.com/ember-labs-org/turkiye-electrification-simulator.git ../elektrifikasyon-labs
# Usage:           tools/publish_labs.sh [--dry-run] [--no-push] [-m "commit message"]
# Env:             LABS_REPO=/path/to/labs/clone   (default: ../elektrifikasyon-labs next to this repo)
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
LABS=${LABS_REPO:-"$ROOT/../elektrifikasyon-labs"}
DRY=0; PUSH=1; MSG=""
while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1 ;;
    --no-push) PUSH=0 ;;
    -m) shift; MSG=$1 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

die() { echo "publish_labs: $*" >&2; exit 1; }

[ -d "$LABS/.git" ] || die "Labs clone not found at $LABS (clone it there or set LABS_REPO)"
git -C "$LABS" remote get-url origin | grep -q 'ember-labs-org/turkiye-electrification-simulator' \
  || die "$LABS does not point at ember-labs-org/turkiye-electrification-simulator"
# docs/ is fully regenerated below (rsync --delete), so only changes outside docs/ block a publish.
[ -z "$(git -C "$LABS" status --porcelain -- . ":(exclude)docs")" ] || die "Labs clone has uncommitted changes outside docs/; commit or discard them first"
[ -f "$ROOT/docs/index.html" ] || die "docs/index.html missing"

# ---- overlay checks (fail before touching anything) ----
grep -q '<labs-worker>' "$ROOT/labs/config.js" && die "labs/config.js still carries the <labs-worker> placeholder"
python3 - "$ROOT/labs/style.css" "$ROOT/docs/assets/style.css" <<'PY' || die "custom-property sets of labs/style.css and docs/assets/style.css differ"
import re, sys
def toks(p): return set(re.findall(r'--[a-zA-Z0-9-]+(?=\s*:)', open(p, encoding='utf-8').read()))
a, b = toks(sys.argv[1]), toks(sys.argv[2])
if a != b:
    print('only in labs:', sorted(a - b), '\nonly in docs:', sorted(b - a), file=sys.stderr); sys.exit(1)
PY
if command -v osascript >/dev/null 2>&1; then
  osascript -l JavaScript -e "var s=\$.NSString.stringWithContentsOfFileEncodingError('$ROOT/labs/config.js',4,null).js; new Function(s); ''" >/dev/null \
    || die "labs/config.js does not parse as JavaScript"
fi

# ---- sync ----
git -C "$LABS" checkout -q main
git -C "$LABS" pull -q --ff-only origin main
mkdir -p "$LABS/docs"
rsync -a --delete --exclude CNAME --exclude .DS_Store "$ROOT/docs/" "$LABS/docs/"
cp "$ROOT/labs/config.js" "$LABS/docs/config.js"
cp "$ROOT/labs/style.css" "$LABS/docs/assets/style.css"
[ ! -e "$LABS/docs/CNAME" ] || die "CNAME ended up in the Labs tree"

UP=$(git -C "$ROOT" rev-parse --short HEAD)
[ -z "$(git -C "$ROOT" status --porcelain docs labs)" ] || UP="$UP+uncommitted"

cd "$LABS"
git add -A docs
if git diff --cached --quiet; then
  echo "publish_labs: Labs docs/ already up to date with upstream $UP"; exit 0
fi
echo "publish_labs: changes vs Labs main:"
git diff --cached --stat
if [ "$DRY" = 1 ]; then
  git reset -q
  echo "publish_labs: dry run — nothing committed"; exit 0
fi
[ -n "$MSG" ] || MSG="Site update from elektrifikasyon.org ($UP)"
git commit -q -m "$MSG" -m "Mirrored from bsgumus/elektrifikasyon@$UP: docs/ with the Ember Labs overlay (config.js, assets/style.css). Generated by tools/publish_labs.sh."
echo "publish_labs: committed $(git rev-parse --short HEAD) — $MSG"
if [ "$PUSH" = 1 ]; then
  git push -q origin main && echo "publish_labs: pushed to origin main"
else
  echo "publish_labs: not pushed (--no-push)"
fi
